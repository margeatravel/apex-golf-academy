export type TranslationDictionary = typeof translations.en;

/**
 * Resolve a dotted path like "dashboard.nextLesson" against the chosen
 * language, falling back to English if the key is missing in Spanish.
 * If both are missing, returns the key path itself so it's obvious in dev.
 */
export function getTranslation(language: Language, path: string): string {
  const segments = path.split('.');
  const lookup = (root: any, lang: Language): string | undefined => {
    let current: any = root?.[lang];
    for (const seg of segments) {
      if (current == null || typeof current !== 'object') return undefined;
      current = current[seg];
    }
    return typeof current === 'string' ? current : undefined;
  };
  return (
    lookup(extraTranslations, language) ??
    lookup(translations, language) ??
    lookup(extraTranslations, 'en') ??
    lookup(translations, 'en') ??
    path
  );
}